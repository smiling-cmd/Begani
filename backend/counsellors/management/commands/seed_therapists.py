class Command(BaseCommand):
    help = "Seed sample therapists (school counsellors and private therapists)."

    @transaction.atomic
    def handle(self, *args, **options):
        created_users = 0
        created_profiles = 0
        skipped = 0

        for data in THERAPISTS:
            email = data["email"]

            if User.objects.filter(email=email).exists():
                self.stdout.write(self.style.WARNING(f"  skip  {email} (already exists)"))
                skipped += 1
                continue

            user = User.objects.create_user(
                email=email,
                password="changeme123",  # only used for testing
                full_name=data["full_name"],
                role="therapist",
                is_active=True,
            )
            created_users += 1

            profile = TherapistProfile.objects.create(
                user=user,
                type=data["type"],
                category=data["category"],
                display_name=data["display_name"],
                title=data["title"],
                bio=data["bio"],
                approach=data["approach"],
                languages=data["languages"],
                session_length_minutes=data["session_length_minutes"],
                format=data["format"],
                location_text=data["location_text"],
                fee_kes=data["fee_kes"],
                status="approved",
            )
            created_profiles += 1

            TherapistVerification.objects.create(
                therapist=profile,
                registration_body=data["reg_body"],
                registration_number=data["reg_number"],
                licence_expiry=data["licence_expiry"],
                register_checked=True,
                licence_current=True,
                category_matches=True,
                id_matched=True,
                certificates_seen=True,
                verified_at=date(2026, 11, 1),
            )

            self.stdout.write(self.style.SUCCESS(f"  ✓     {email}"))

        self.stdout.write("")
        self.stdout.write(self.style.SUCCESS(
            f"Done. Created {created_users} users, {created_profiles} profiles, skipped {skipped}."
        ))